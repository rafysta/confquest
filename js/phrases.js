const Phrases = {
  /** 全カードの平坦なリスト */
  all() {
    if (!this._all) {
      this._all = [];
      PHRASE_UNITS.forEach((u) => u.cards.forEach((c) => {
        this._all.push(Object.assign({ unitId: u.id, lang: u.lang }, c));
      }));
    }
    return this._all;
  },
  byId(id) { return this.all().find((c) => c.id === id); },
  unit(id) { return PHRASE_UNITS.find((u) => u.id === id); },

  /* ---------- ここから下は「いまのプロフィールで見えるぶん」だけを返す ----------
   * all()/byId() は全部を返したまま(バックアップの復元や、
   * もう一方のプロフィールのカードを引くのに必要)。
   * 画面に並べるもの・復習に出すものは、必ずこちらを通すこと。 */

  /** いまのプロフィール向けのユニット(言語で絞る) */
  units(lang) {
    return PHRASE_UNITS.filter((u) => u.lang === lang)
      .filter((u) => typeof Profile === 'undefined' || Profile.showsUnit(u));
  },
  /** いまのプロフィール向けのユニット(全言語) */
  allUnits() {
    return PHRASE_UNITS.filter((u) => typeof Profile === 'undefined' || Profile.showsUnit(u));
  },
  /** いまのプロフィール向けのカード(言語で絞る) */
  byLang(lang) {
    const ids = new Set(this.units(lang).map((u) => u.id));
    return this.all().filter((c) => ids.has(c.unitId));
  },
  /** いまのプロフィール向けのカード(全言語) */
  inCourse() {
    const ids = new Set(this.allUnits().map((u) => u.id));
    return this.all().filter((c) => ids.has(c.unitId));
  }
};
